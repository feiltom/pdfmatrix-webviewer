// Builds dist/: the ESM and CommonJS bundles, the pdf.js runtime files they load, and the asset
// table that addresses those files with `new URL(..., import.meta.url)`.
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const pdfjs = join(root, 'node_modules', 'pdfjs-dist');
const dist = join(root, 'dist');
// Under assets/webviewer/: apps built for WebViewer already give that path long-lived cache headers
// and keep it out of service worker precaching.
const vendor = join(dist, 'assets', 'webviewer', 'pdfjs');

rmSync(dist, { recursive: true, force: true });
mkdirSync(vendor, { recursive: true });

// pdf.js runtime. The worker gets a .js name: some servers send .mjs with a non-JS MIME type and
// module workers refuse it.
copyFileSync(join(pdfjs, 'build', 'pdf.min.mjs'), join(vendor, 'pdf.min.mjs'));
copyFileSync(join(pdfjs, 'build', 'pdf.worker.min.mjs'), join(vendor, 'pdf.worker.min.js'));
copyFileSync(join(pdfjs, 'LICENSE'), join(vendor, 'LICENSE'));
for (const dir of ['cmaps', 'standard_fonts', 'wasm']) {
    cpSync(join(pdfjs, dir), join(vendor, dir), { recursive: true });
}

const files = (dir, filter) => readdirSync(join(vendor, dir)).filter(filter).sort();
const entries = (dir, filter) => files(dir, filter)
    .map((f) => `        ${JSON.stringify(f)}: new URL(${JSON.stringify(`./assets/webviewer/pdfjs/${dir}/${f}`)}, import.meta.url).href,`)
    .join('\n');

const generated = `// Generated by scripts/build.mjs. Each file is referenced with a literal \`new URL()\` so that
// bundlers emit it; the table is built lazily because CommonJS consumers have no import.meta.
export const workerUrl = () => new URL('./assets/webviewer/pdfjs/pdf.worker.min.js', import.meta.url).href;

export const assetTable = () => ({
    cMapUrl: {
${entries('cmaps', (f) => f.endsWith('.bcmap'))}
    },
    standardFontDataUrl: {
${entries('standard_fonts', (f) => /\.(pfb|ttf)$/.test(f))}
    },
    wasmUrl: {
${entries('wasm', (f) => /\.(wasm|js)$/.test(f))}
    },
});
`;
mkdirSync(join(root, 'src', 'generated'), { recursive: true });
writeFileSync(join(root, 'src', 'generated', 'assets.js'), generated);

const common = {
    entryPoints: [join(root, 'src', 'index.js')],
    bundle: true,
    platform: 'browser',
    target: 'es2020',
    external: ['./assets/webviewer/pdfjs/*'],
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: `/*! ${pkg.name} ${pkg.version} | Apache-2.0 | bundles pdf.js (Apache-2.0) in ./assets/webviewer/pdfjs */` },
};

// `VERSION` in src/index.js is a placeholder string: stamp the package version after bundling.
const stamp = (file) => writeFileSync(file, readFileSync(file, 'utf8').replaceAll('__VERSION__', pkg.version));

await build({ ...common, format: 'esm', outfile: join(dist, 'webviewer.js') });
await build({
    ...common,
    format: 'cjs',
    outfile: join(dist, 'webviewer.cjs'),
    logOverride: { 'empty-import-meta': 'silent' },
    // `require('…')` returns the function itself, like the original package; `.default` keeps
    // transpiled `import WebViewer from` working.
    footer: { js: 'module.exports = module.exports.default; module.exports.default = module.exports;' },
});
stamp(join(dist, 'webviewer.js'));
stamp(join(dist, 'webviewer.cjs'));
copyFileSync(join(root, 'src', 'webviewer.d.ts'), join(dist, 'webviewer.d.ts'));

console.log(`built ${pkg.name} ${pkg.version}`);
